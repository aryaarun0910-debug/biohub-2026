"""H1-T — provenance-preserving EXTERNAL division event set from Zebrahub tracks.

Rebuilds the external training surface the earlier `divevents_extract.py` threw away. That
extraction emitted scale-free mother-centric trajectories with "no absolute coordinates, no
embryo id" by design, so its tensors could never be joined back to imagery, to a proposer, or
to anything else. This script keeps every join key.

Two properties make this set usable where the previous one was not:

1. HARD NEGATIVES COME FROM THE DEPLOYED PROPOSER.  The candidate surface is generated by
   importing `phaseb_h0c_replay.shortlist` verbatim (frozen config hash 04eeac97500d:
   parent <= 15 um, sister <= 15 um, kNN flow k=16/min=4, rank by flow-midpoint residual,
   top-3 per mother).  Nothing is retuned.  The old negatives were "genuine continuation +
   nearby fake second daughter", a distribution the deployment proposer never emits.

2. THE GRAPH THE PROPOSER SEES IS A PREDICTION, NOT GROUND TRUTH.  Feeding the proposer the
   GT lineage would make `competing_parents`/`persist`/`mother_track_age` trivially separate
   positives (a true daughter pair would already be wired to its mother), whereas on the
   competition side 97% of shortlist rows require stealing a parent.  So a GT-FREE one-to-one
   linker is run first (greedy flow-corrected assignment, in-degree <= 1, out-degree <= 1,
   gate = E0c's inherited 10.5 um migration cap) and the GT tracks are used ONLY for labels.

UNITS (documented, not fitted):
  ZSNS003/004/005 track coordinates are LEVEL-0 VOXELS -> multiplied by the OME-Zarr
  `coordinateTransformations` scale (z 1.24, y 0.439, x 0.439 um) published in
  `<embryo>.ome.zarr/.zattrs`.
  ZSNS001 track coordinates are ALREADY MICRONS (its extent 527/927/1043 um matches the
  level-0 array 448x2174x2423 at that scale; the voxel reading would exceed the array).
  Verified by `--check-units`.

LABELS mirror `phaseb_h1a_census.py` exactly:
  positive           mother's GT track divides at t and this pair is its true daughter pair
  reliable_negative  mother's GT track continues (out-degree 1), or divides but wrong pair
  unlabeled          mother's GT track ends at t (out-degree 0)
  metric_visible     out-degree >= 1

Usage:
  .venv\\Scripts\\python.exe scripts\\win_bet\\h1t_zebrahub_events.py --check-units
  .venv\\Scripts\\python.exe scripts\\win_bet\\h1t_zebrahub_events.py --prep
  .venv\\Scripts\\python.exe scripts\\win_bet\\h1t_zebrahub_events.py --build --workers 6
"""
