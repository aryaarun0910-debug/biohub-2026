def build_audit_notebook(spec: AuditSpec) -> dict[str, Any]:
    """One cell, no payload, no Biohub-X import, and the fields nbformat requires."""
    import json

    fixture, description = blosc_fixture()
    source = (
        AUDIT_CELL.replace("__AUDIT_JSON__", json.dumps(spec.to_dict(), sort_keys=True))
        .replace("__CLOSURE_JSON__", json.dumps(list(RUNTIME_CLOSURE)))
        .replace("__BLOSC_FIXTURE__", fixture)
        .replace("__FIXTURE_DESCRIPTION__", description)
    )
    for forbidden in ("import biohubx", "from biohubx", "/kaggle/input"):
        if forbidden in source:
            raise AuditError(f"the audit notebook must not contain {forbidden!r}")
    return {
        "cells": [
            {
                "id": "biohubx-environment-audit",
                "cell_type": "code",
                "execution_count": None,
                "metadata": {},
                "outputs": [],
                "source": source.splitlines(keepends=True),
            }
        ],
        "metadata": {
            "kernelspec": {
                "display_name": "Python 3",
                "language": "python",
                "name": "python3",
            },
            "language_info": {"name": "python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


