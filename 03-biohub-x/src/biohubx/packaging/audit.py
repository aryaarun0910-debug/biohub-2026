"""A diagnostic kernel that measures the Kaggle runtime and touches nothing else.

E03-SMOKE-02 died on ``import zarr``, and one traceback is not enough to build a
wheelhouse from. A wheel has to match the target's Python version, platform tag
and ABI, and none of those have been measured; they have only been inferred.

So this package answers what is actually there. It reads no competition data,
trains nothing, requests no accelerator, and imports no part of Biohub-X, because
a diagnostic that depends on the thing it is diagnosing cannot run when that
thing is missing. Every probe is wrapped: a package that is absent is reported as
absent and the audit continues, since a crash on the first gap would tell us only
about that gap.

The blosc probe is the sharp one. The competition volumes are zarr v3 with a
blosc/zstd/bitshuffle codec at typesize 2, so this carries a small buffer encoded
exactly that way and asks the target to decode it. Importability is not the
question; decoding the real codec is.

Consumer: ``biohubx package audit``.
"""

