"""Every import Biohub-X reaches for at runtime, plus the codec stack beneath it.

Import names, not distribution names, because importability is what fails. The
audit reports distribution versions separately from a full `importlib.metadata`
listing.
"""


class AuditError(ValueError):
    """The audit package could not be built."""


@dataclass(frozen=True, slots=True)
class AuditSpec:
    """What the diagnostic declares about itself."""

    audit_id: str
    commit: str
    kernel: str
    runtime_ceiling_seconds: int

    def to_dict(self) -> dict[str, Any]:
        return {
            "audit_id": self.audit_id,
            "commit": self.commit,
            "kernel": self.kernel,
            "runtime_ceiling_seconds": self.runtime_ceiling_seconds,
        }


def blosc_fixture() -> tuple[str, str]:
    """A buffer encoded with the competition's own codec, and its expected content.

    Built here so the target does not need an encoder to prove it has a decoder.
    Returns the base64 payload and a description of what decoding it should yield.
    """
    try:
        import numpy as np
        from numcodecs import Blosc
    except ImportError as exc:  # pragma: no cover - the build machine has both
        raise AuditError("numcodecs is needed to build the decode fixture") from exc

    codec = Blosc(cname="zstd", clevel=1, shuffle=Blosc.BITSHUFFLE, blocksize=0)
    original = np.arange(256, dtype=np.uint16)
    encoded = codec.encode(original.tobytes())
    return base64.b64encode(encoded).decode("ascii"), "uint16 arange(256)"


def audit_kernel_metadata(kernel: str = AUDIT_KERNEL, title: str = AUDIT_TITLE) -> dict[str, Any]:
    """CPU only, no accelerator, no internet, no sources of any kind.

    A diagnostic that could reach the network would measure a machine nobody will
    train on, and one with data sources attached would risk touching competition
    bytes for no reason.
    """
    return {
        "id": kernel,
        "title": title,
        "code_file": "run.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": False,
        "enable_internet": False,
        "dataset_sources": [],
        "kernel_sources": [],
        "model_sources": [],
        "competition_sources": [],
    }


